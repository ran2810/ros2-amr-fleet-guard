#!/usr/bin/env python3
"""Fleet traffic manager for the warehouse AMRs.

The task allocator remains in manager.py.  Robot agents ask this node to move one leg (to pickup,
drop, or dock).  The node:

  1. plans on a small warehouse lane graph generated by generate_world.py,
  2. treats graph corridors / rack aisles as capacity-one resources,
  3. reroutes around resources reserved by another robot when an alternative exists,
  4. atomically reserves every constrained resource on the selected leg (deadlock prevention),
  5. executes the approved graph route through Nav2 NavigateThroughPoses,
  6. releases every reservation on success, failure, or cancellation.

A wait-for graph and cycle detector are kept as a watchdog.  With atomic per-leg acquisition a
resource deadlock should be prevented by construction; if a cycle is ever observed, the newest
waiter yields and replans rather than forcing release of a resource under a moving robot.

This first version is intentionally conservative.  Once stable, reservation scope can be reduced
from the whole leg to a 1-edge look-ahead window to improve fleet throughput.
"""
from __future__ import annotations

import heapq
import math
import os
import threading
import time
from dataclasses import dataclass
from typing import Dict, Iterable, List, Optional, Sequence, Set, Tuple

import rclpy
import yaml
from action_msgs.msg import GoalStatus
from ament_index_python.packages import get_package_share_directory
from geometry_msgs.msg import PoseStamped
from nav2_msgs.action import NavigateThroughPoses
from rclpy.action import ActionClient, ActionServer, CancelResponse, GoalResponse
from rclpy.callback_groups import ReentrantCallbackGroup
from rclpy.executors import MultiThreadedExecutor
from rclpy.node import Node
from warehouse_msgs.action import TrafficNavigate
from warehouse_msgs.msg import RobotState

Point = Tuple[float, float]


@dataclass(frozen=True)
class Edge:
    edge_id: str
    src: str
    dst: str
    resource: str
    length: float


@dataclass
class RoutePlan:
    nodes: List[str]
    edges: List[Edge]
    cost: float


@dataclass
class Lease:
    robot_id: str
    route_id: str
    acquired_at: float


class TrafficGraph:
    def __init__(self, path: str):
        with open(path) as f:
            data = yaml.safe_load(f)
        self.frame_id = data.get('frame_id', 'map')
        routing = data.get('routing', {})
        self.waypoint_spacing = float(routing.get('waypoint_spacing', 0.6))
        self.nearest_nodes = int(routing.get('nearest_nodes', 1))
        self.anchor_snap_dist = float(routing.get('anchor_snap_dist', 0.75))
        self.lock_route_nodes = bool(routing.get('lock_route_nodes', True))
        self.nodes: Dict[str, Point] = {
            str(name): (float(v['x']), float(v['y'])) for name, v in data['nodes'].items()
        }
        self.resources: Dict[str, Set[str]] = {
            str(name): set(v.get('conflicts_with', []) or [])
            for name, v in (data.get('resources') or {}).items()
        }
        self.adj: Dict[str, List[Edge]] = {name: [] for name in self.nodes}
        for raw in data['edges']:
            src, dst = str(raw['from']), str(raw['to'])
            resource = str(raw.get('resource') or '')
            length = math.dist(self.nodes[src], self.nodes[dst])
            edge = Edge(str(raw['id']), src, dst, resource, length)
            self.adj[src].append(edge)
            if bool(raw.get('bidirectional', True)):
                self.adj[dst].append(Edge(edge.edge_id, dst, src, resource, length))

    @staticmethod
    def _d(a: Point, b: Point) -> float:
        return math.hypot(a[0] - b[0], a[1] - b[1])

    def _nearest(self, p: Point) -> List[str]:
        ranked = sorted((self._d(p, xy), name) for name, xy in self.nodes.items())
        # Task endpoints and docks are explicit graph nodes. If the robot/goal is already on one,
        # snap to that single node so planning cannot choose a cheaper unreserved diagonal shortcut.
        if ranked and ranked[0][0] <= self.anchor_snap_dist:
            return [ranked[0][1]]
        return [name for _, name in ranked[:max(1, self.nearest_nodes)]]

    def _astar(self, start: str, goal: str, blocked: Set[str]) -> Optional[RoutePlan]:
        if start == goal:
            return RoutePlan([start], [], 0.0)
        queue = [(0.0, 0.0, start)]
        came: Dict[str, Tuple[str, Edge]] = {}
        best = {start: 0.0}
        while queue:
            _, g, node = heapq.heappop(queue)
            if g > best.get(node, math.inf) + 1e-9:
                continue
            if node == goal:
                nodes = [goal]
                edges: List[Edge] = []
                cur = goal
                while cur != start:
                    prev, edge = came[cur]
                    edges.append(edge)
                    nodes.append(prev)
                    cur = prev
                nodes.reverse()
                edges.reverse()
                return RoutePlan(nodes, edges, g)
            for edge in self.adj[node]:
                if edge.resource and edge.resource in blocked:
                    continue
                # Intermediate graph nodes are also capacity-one intersection resources.
                if self.lock_route_nodes and edge.dst != goal and f'node:{edge.dst}' in blocked:
                    continue
                ng = g + edge.length
                if ng + 1e-9 >= best.get(edge.dst, math.inf):
                    continue
                best[edge.dst] = ng
                came[edge.dst] = (node, edge)
                h = self._d(self.nodes[edge.dst], self.nodes[goal])
                heapq.heappush(queue, (ng + h, ng, edge.dst))
        return None

    def plan(self, start_xy: Point, goal_xy: Point, blocked: Set[str]) -> Optional[RoutePlan]:
        """Best graph route including the off-graph connector distances at each end."""
        best_plan = None
        best_total = math.inf
        for s in self._nearest(start_xy):
            for g in self._nearest(goal_xy):
                plan = self._astar(s, g, blocked)
                if plan is None:
                    continue
                total = self._d(start_xy, self.nodes[s]) + plan.cost + self._d(self.nodes[g], goal_xy)
                if total < best_total:
                    best_total = total
                    best_plan = plan
        if best_plan is not None:
            best_plan.cost = best_total
        return best_plan

    def route_resources(self, plan: RoutePlan) -> List[str]:
        out: List[str] = []
        seen: Set[str] = set()
        for edge in plan.edges:
            if edge.resource and edge.resource not in seen:
                out.append(edge.resource)
                seen.add(edge.resource)
        if self.lock_route_nodes:
            # Do not lock the first/last graph node. The fleet manager already serialises task
            # stations, and excluding endpoints prevents a robot's current location from becoming
            # impossible to reserve. Internal intersections are still mutually exclusive.
            for node in plan.nodes[1:-1]:
                resource = f'node:{node}'
                if resource not in seen:
                    out.append(resource)
                    seen.add(resource)
        return out

    def dense_points(self, start_xy: Point, goal: Tuple[float, float, float], plan: RoutePlan) -> List[Tuple[float, float, float]]:
        """Dense via-points keep NavFn close to the fleet-approved graph rather than taking shortcuts."""
        raw: List[Point] = [start_xy]
        raw.extend(self.nodes[n] for n in plan.nodes)
        raw.append((goal[0], goal[1]))
        # Remove adjacent duplicates.
        compact = [raw[0]]
        for p in raw[1:]:
            if self._d(compact[-1], p) > 0.05:
                compact.append(p)
        if len(compact) == 1:
            return [(goal[0], goal[1], goal[2])]

        points: List[Point] = []
        for a, b in zip(compact, compact[1:]):
            dist = self._d(a, b)
            steps = max(1, int(math.ceil(dist / max(0.2, self.waypoint_spacing))))
            for i in range(1, steps + 1):
                t = i / steps
                points.append((a[0] + t * (b[0] - a[0]), a[1] + t * (b[1] - a[1])))

        result: List[Tuple[float, float, float]] = []
        for i, (x, y) in enumerate(points):
            if i == len(points) - 1:
                yaw = goal[2]
            else:
                nx, ny = points[i + 1]
                yaw = math.atan2(ny - y, nx - x)
            result.append((x, y, yaw))
        return result


class ReservationTable:
    def __init__(self, conflicts: Dict[str, Set[str]], logger):
        self.conflicts = conflicts
        self.logger = logger
        self.lock = threading.RLock()
        self.owners: Dict[str, Lease] = {}
        self.wait_for: Dict[str, Set[str]] = {}
        self.wait_since: Dict[str, float] = {}
        self.yield_until: Dict[str, float] = {}

    def _blockers_unlocked(self, resource: str, robot_id: str) -> Set[str]:
        blockers = set()
        lease = self.owners.get(resource)
        if lease is not None and lease.robot_id != robot_id:
            blockers.add(lease.robot_id)
        for other in self.conflicts.get(resource, set()):
            lease = self.owners.get(other)
            if lease is not None and lease.robot_id != robot_id:
                blockers.add(lease.robot_id)
        return blockers

    def blockers(self, resources: Iterable[str], robot_id: str) -> Set[str]:
        with self.lock:
            out: Set[str] = set()
            for resource in resources:
                out |= self._blockers_unlocked(resource, robot_id)
            return out

    def blocked_resources(self, robot_id: str) -> Set[str]:
        """Resources (including conflict partners) that the robot must not plan through right now."""
        with self.lock:
            known = set(self.conflicts) | set(self.owners)
            return {r for r in known if self._blockers_unlocked(r, robot_id)}

    def try_reserve_all(self, resources: Sequence[str], robot_id: str, route_id: str) -> Tuple[bool, Set[str]]:
        """Atomic acquisition: either the complete leg is reserved or nothing is changed."""
        with self.lock:
            blockers: Set[str] = set()
            for resource in resources:
                blockers |= self._blockers_unlocked(resource, robot_id)
            if blockers:
                return False, blockers
            now = time.monotonic()
            for resource in resources:
                self.owners[resource] = Lease(robot_id, route_id, now)
            self.clear_wait(robot_id)
            return True, set()

    def release_route(self, robot_id: str, route_id: str):
        with self.lock:
            for resource in [r for r, lease in self.owners.items()
                             if lease.robot_id == robot_id and lease.route_id == route_id]:
                del self.owners[resource]
            self.clear_wait(robot_id)

    def set_wait(self, robot_id: str, blockers: Set[str]):
        with self.lock:
            if blockers:
                self.wait_for[robot_id] = set(blockers)
                self.wait_since.setdefault(robot_id, time.monotonic())
            else:
                self.clear_wait(robot_id)

    def clear_wait(self, robot_id: str):
        self.wait_for.pop(robot_id, None)
        self.wait_since.pop(robot_id, None)

    def detect_cycle(self) -> List[str]:
        with self.lock:
            graph = {k: set(v) for k, v in self.wait_for.items()}
        visiting: Set[str] = set()
        visited: Set[str] = set()
        stack: List[str] = []

        def dfs(node: str) -> Optional[List[str]]:
            if node in visiting:
                i = stack.index(node)
                return stack[i:] + [node]
            if node in visited:
                return None
            visiting.add(node)
            stack.append(node)
            for nxt in graph.get(node, set()):
                cycle = dfs(nxt)
                if cycle:
                    return cycle
            stack.pop()
            visiting.remove(node)
            visited.add(node)
            return None

        for node in list(graph):
            cycle = dfs(node)
            if cycle:
                return cycle
        return []

    def resolve_cycle_by_yield(self, cycle: Sequence[str], seconds: float = 2.0) -> Optional[str]:
        """Yield the newest waiter only; never force-release an occupied corridor."""
        if not cycle:
            return None
        robots = list(dict.fromkeys(cycle))
        with self.lock:
            victim = max(robots, key=lambda r: self.wait_since.get(r, -math.inf))
            self.yield_until[victim] = time.monotonic() + seconds
            self.clear_wait(victim)
        self.logger.warning(f'deadlock watchdog: {" -> ".join(cycle)}; {victim} yields and replans')
        return victim

    def must_yield(self, robot_id: str) -> float:
        with self.lock:
            return max(0.0, self.yield_until.get(robot_id, 0.0) - time.monotonic())


class TrafficManager(Node):
    def __init__(self):
        super().__init__('traffic_manager')
        p = self.declare_parameter
        self.robot_ids = list(p('robot_ids', ['robot_1', 'robot_2']).value)
        self.wait_retry = float(p('wait_retry', 1.0).value)
        self.max_wait = float(p('max_wait', 90.0).value)
        self.nav_timeout = float(p('nav_timeout', 300.0).value)
        self.max_replans = int(p('max_replans', 2).value)
        default_graph = os.path.join(get_package_share_directory('warehouse_gazebo'), 'config', 'traffic.yaml')
        graph_path = str(p('traffic_file', default_graph).value)
        self.graph = TrafficGraph(graph_path)
        self.reservations = ReservationTable(self.graph.resources, self.get_logger())
        self.states: Dict[str, RobotState] = {}
        self.state_lock = threading.RLock()
        self.active_lock = threading.RLock()
        self.active_robots: Set[str] = set()

        cb = ReentrantCallbackGroup()
        self.nav_clients = {
            rid: ActionClient(self, NavigateThroughPoses, f'/{rid}/navigate_through_poses', callback_group=cb)
            for rid in self.robot_ids
        }
        for rid in self.robot_ids:
            self.create_subscription(RobotState, f'/{rid}/robot_state',
                                     lambda msg, r=rid: self._on_state(r, msg), 10, callback_group=cb)
        self.server = ActionServer(
            self, TrafficNavigate, '/fleet/traffic_navigate', execute_callback=self._execute,
            goal_callback=self._on_goal, cancel_callback=self._on_cancel, callback_group=cb)
        self.get_logger().info(
            f'traffic manager up: {len(self.graph.nodes)} graph nodes, '
            f'{sum(len(v) for v in self.graph.adj.values()) // 2} bidirectional edges, robots {self.robot_ids}')

    def _on_state(self, rid: str, msg: RobotState):
        with self.state_lock:
            self.states[rid] = msg

    def _on_goal(self, request: TrafficNavigate.Goal):
        if request.robot_id not in self.nav_clients:
            self.get_logger().warning(f'traffic request rejected: unknown robot {request.robot_id}')
            return GoalResponse.REJECT
        with self.active_lock:
            if request.robot_id in self.active_robots:
                self.get_logger().warning(f'traffic request rejected: {request.robot_id} already has an active leg')
                return GoalResponse.REJECT
            self.active_robots.add(request.robot_id)
        return GoalResponse.ACCEPT

    @staticmethod
    def _on_cancel(_goal_handle):
        return CancelResponse.ACCEPT

    def _state_xy(self, rid: str) -> Optional[Point]:
        with self.state_lock:
            s = self.states.get(rid)
            return None if s is None else (float(s.x), float(s.y))

    def _feedback(self, gh, state: str, active_resource: str = '', waiting_for: str = ''):
        fb = TrafficNavigate.Feedback()
        fb.traffic_state = state
        fb.active_resource = active_resource
        fb.waiting_for = waiting_for
        gh.publish_feedback(fb)

    def _pose_msgs(self, points: Sequence[Tuple[float, float, float]]) -> List[PoseStamped]:
        out = []
        stamp = self.get_clock().now().to_msg()
        for x, y, yaw in points:
            p = PoseStamped()
            p.header.frame_id = self.graph.frame_id
            p.header.stamp = stamp
            p.pose.position.x, p.pose.position.y = float(x), float(y)
            p.pose.orientation.z = math.sin(yaw / 2.0)
            p.pose.orientation.w = math.cos(yaw / 2.0)
            out.append(p)
        return out

    @staticmethod
    def _fill_nav_goal(goal: NavigateThroughPoses.Goal, poses: List[PoseStamped]):
        """Jazzy uses PoseStamped[]; newer Nav2 uses nav_msgs/Goals. Support both for easy migration."""
        if hasattr(goal.poses, 'goals'):
            goal.poses.header.frame_id = 'map'
            goal.poses.goals = poses
        else:
            goal.poses = poses

    def _navigate_through(self, rid: str, poses: List[PoseStamped], traffic_gh) -> Tuple[bool, str]:
        client = self.nav_clients[rid]
        if not client.wait_for_server(timeout_sec=5.0):
            return False, 'NavigateThroughPoses server unavailable'
        goal = NavigateThroughPoses.Goal()
        self._fill_nav_goal(goal, poses)
        send = client.send_goal_async(goal)
        t0 = time.monotonic()
        while not send.done():
            if traffic_gh.is_cancel_requested:
                return False, 'canceled'
            if time.monotonic() - t0 > 10.0:
                return False, 'NavigateThroughPoses goal acknowledgement timeout'
            time.sleep(0.05)
        handle = send.result()
        if handle is None or not handle.accepted:
            return False, 'NavigateThroughPoses goal rejected'
        result = handle.get_result_async()
        while not result.done():
            if traffic_gh.is_cancel_requested:
                handle.cancel_goal_async()
                return False, 'canceled'
            if time.monotonic() - t0 > self.nav_timeout:
                handle.cancel_goal_async()
                return False, 'NavigateThroughPoses timeout'
            time.sleep(0.1)
        wrapped = result.result()
        if wrapped.status == GoalStatus.STATUS_SUCCEEDED:
            return True, 'done'
        msg = getattr(wrapped.result, 'error_msg', '') or f'Nav2 status {wrapped.status}'
        return False, msg

    def _execute(self, gh):
        req = gh.request
        rid = req.robot_id
        route_id = f'{rid}:{req.task_id}:{req.stage}:{time.monotonic_ns()}'
        result = TrafficNavigate.Result()
        result.success = False
        result.route_edges = []
        deadline = time.monotonic() + self.max_wait
        replans = 0
        goal = (float(req.goal_x), float(req.goal_y), float(req.goal_yaw))
        try:
            while rclpy.ok():
                if gh.is_cancel_requested:
                    self.reservations.release_route(rid, route_id)
                    result.message = 'canceled'
                    gh.canceled()
                    return result

                delay = self.reservations.must_yield(rid)
                if delay > 0.0:
                    self._feedback(gh, 'DEADLOCK_YIELD')
                    time.sleep(min(delay, self.wait_retry))
                    continue

                start = self._state_xy(rid)
                if start is None:
                    if time.monotonic() >= deadline:
                        result.message = 'no robot state received'
                        gh.abort()
                        return result
                    self._feedback(gh, 'WAITING_FOR_ROBOT_STATE')
                    time.sleep(self.wait_retry)
                    continue

                blocked = self.reservations.blocked_resources(rid)
                plan = self.graph.plan(start, (goal[0], goal[1]), blocked)
                # self.get_logger().info(
                #     f'{rid}: start={start}, '
                #     f'graph_start={plan.nodes[0]}, '
                #     f'graph_start_xy={self.graph.nodes[plan.nodes[0]]}, '
                #     f'goal={goal}, nodes={plan.nodes}'
                # )
                if plan is None:
                    # Find what the unconstrained shortest route would need so the wait-for graph
                    # contains useful owners.  If another graph route exists, the constrained plan
                    # above would already have selected it, i.e. this branch means "wait".
                    desired = self.graph.plan(start, (goal[0], goal[1]), set())
                    if desired is None:
                        result.message = 'no route in traffic graph'
                        gh.abort()
                        return result
                    desired_resources = self.graph.route_resources(desired)
                    blockers = self.reservations.blockers(desired_resources, rid)
                    self.reservations.set_wait(rid, blockers)
                    cycle = self.reservations.detect_cycle()
                    if cycle:
                        self.reservations.resolve_cycle_by_yield(cycle)
                    if time.monotonic() >= deadline:
                        result.message = 'traffic wait timeout: ' + ','.join(sorted(blockers))
                        gh.abort()
                        return result
                    waiting = ','.join(sorted(blockers)) or 'reserved corridor'
                    self._feedback(gh, 'WAITING_FOR_TRAFFIC', waiting_for=waiting)
                    time.sleep(self.wait_retry)
                    continue

                resources = self.graph.route_resources(plan)
                ok, blockers = self.reservations.try_reserve_all(resources, rid, route_id)
                if not ok:  # another robot won the race between planning and acquisition
                    self.reservations.set_wait(rid, blockers)
                    self._feedback(gh, 'WAITING_FOR_TRAFFIC', waiting_for=','.join(sorted(blockers)))
                    time.sleep(self.wait_retry)
                    continue

                result.route_edges = [e.edge_id for e in plan.edges]
                active = ','.join(resources)
                self.get_logger().info(
                    f'{rid}: traffic route {req.stage} -> ({goal[0]:.1f},{goal[1]:.1f}); '
                    f'edges={result.route_edges}, reserved={resources}')
                self._feedback(gh, 'NAVIGATING', active_resource=active)
                points = self.graph.dense_points(start, goal, plan)
                poses = self._pose_msgs(points)
                nav_ok, nav_msg = self._navigate_through(rid, poses, gh)
                if gh.is_cancel_requested or nav_msg == 'canceled':
                    result.message = 'canceled'
                    gh.canceled()
                    return result
                if nav_ok:
                    result.success, result.message = True, 'done'
                    gh.succeed()
                    return result
                replans += 1
                self.get_logger().warning(f'{rid}: traffic-approved Nav2 route failed: {nav_msg}')
                if replans > self.max_replans:
                    result.message = nav_msg
                    gh.abort()
                    return result
                # Keep the current leg's reservations while replanning.  A Nav2 abort can leave the
                # physical robot inside a corridor; releasing immediately would let another robot
                # reserve that same aisle before this robot has recovered / moved away.
                self._feedback(gh, 'REPLANNING')
                time.sleep(self.wait_retry)
        finally:
            self.reservations.release_route(rid, route_id)
            with self.active_lock:
                self.active_robots.discard(rid)


def main():
    rclpy.init()
    node = TrafficManager()
    executor = MultiThreadedExecutor(num_threads=12)
    executor.add_node(node)
    try:
        executor.spin()
    except KeyboardInterrupt:
        pass
    node.destroy_node()
    rclpy.try_shutdown()


if __name__ == '__main__':
    main()
