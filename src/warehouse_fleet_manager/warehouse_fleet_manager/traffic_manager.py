#!/usr/bin/env python3
"""Fleet traffic manager for the warehouse AMRs.

The task allocator remains in manager.py. Robot agents ask this node to move one leg (to pickup,
drop, or dock). The node:

  1. plans on the warehouse lane graph generated by generate_world.py,
  2. treats graph corridors / rack aisles as capacity-one resources,
  3. reserves a rolling window instead of the complete navigation leg,
  4. acquires the next window before releasing the previous one,
  5. reroutes around currently blocked resources when an alternative exists,
  6. executes one graph edge at a time through Nav2 NavigateThroughPoses,
  7. releases resources behind the robot as it progresses.

The default reservation window is two distinct traffic resources: the resource about to be
traversed plus one look-ahead resource. A physical rack aisle may span multiple graph edges that
share the same resource; in that case the window automatically extends through the complete aisle
and also reserves its exit before entry. This improves concurrency compared with whole-leg
reservations while still preventing opposite-direction admission into a capacity-one aisle.

If a future window cannot be acquired, the robot waits at the current graph node. Reservations that
are no longer physically needed are released, while the most recently traversed resource and the
current node lock are retained conservatively. A wait-for graph remains as a deadlock watchdog;
the traffic manager never force-releases a resource that may still contain a robot.
"""
